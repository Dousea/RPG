"""Loot tables for the containers of the starting places (spec 25)."""

from typing import NamedTuple


class LootTable(NamedTuple):
    """One table: `rolls` passes over `items`, preceded by the junk pass; entries are (name, chance)."""

    rolls: int
    items: tuple[tuple[str, float], ...]
    junk_rolls: int
    junk_items: tuple[tuple[str, float], ...]
    shop: bool


class ProcedureEntry(NamedTuple):
    """A procedural table a container may pick: used at most `max_picks` times a room, forced while `min_picks` is 1."""

    table: str
    min_picks: int
    max_picks: int
    weight: int


class ContainerSource(NamedTuple):
    """What a container type rolls: a pick among procedural tables, or its own table when there are none."""

    procedures: tuple[ProcedureEntry, ...]
    table: LootTable | None


