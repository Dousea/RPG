def _symmetric(
    pairs: dict[BodyLocation, set[BodyLocation]],
) -> dict[BodyLocation, frozenset[BodyLocation]]:
    both: dict[BodyLocation, set[BodyLocation]] = {}
    for first, others in pairs.items():
        for second in others:
            both.setdefault(first, set()).add(second)
            both.setdefault(second, set()).add(first)
    return {location: frozenset(others) for location, others in both.items()}


